--[[
====================================================================
 绘制曲线演示
====================================================================

这个脚本演示「工具 → 曲线」的用法，不需要串口，也不需要接收数据。

运行步骤：
  1. 在「运行脚本」页选中本脚本，点运行；
  2. 切到右侧「工具 → 曲线」查看曲线；
  3. 如果曲线没有铺满，点一下「查看全图」重新适配 Y 轴。

实现说明：
  - apiAddPoint(值, 线号)：线号 0~9，最多同时显示 10 条曲线；
  - 每条曲线最多保留最近 1000 个点，超过后自动丢弃最早的点；
  - X 轴是样本序号，不是时间；Y 轴是传入的数值；
  - 「清空图表」会把所有曲线数据归零；「切换主题」切换绘图区配色。

想改成自己的数据：
  - 把 value 换成从串口解析出来的数值；
  - 把 line 换成 0~9 中你想用的曲线编号；
  - 如果希望一直运行，把 for 循环改成 while true 即可。
]]

local points = 200 -- 生成多少个点
local delayMs = 100 -- 每个点间隔多少毫秒（200 × 100ms = 20 秒）

log.info("曲线演示", "开始生成 " .. points .. " 个点，请切换到 工具 → 曲线")

sys.taskInit(function()
    for i = 1, points do
        local x = i / 10

        -- 第一条曲线：正弦波，范围约 -100 ~ 100
        apiAddPoint(math.sin(x) * 100, 1)

        -- 第二条曲线：余弦波，范围约 -100 ~ 100
        apiAddPoint(math.cos(x) * 100, 2)

        sys.wait(delayMs)
    end

    log.info("曲线演示", "完成，可点「查看全图」查看完整波形")
end)